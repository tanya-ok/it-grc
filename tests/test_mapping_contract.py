"""Offline tests for scripts/check_mapping_contract.py. The library documents here are
synthetic: they are generated from this repository's own mapping and are not copies of the
upstream file. No network is used."""

from __future__ import annotations

import contextlib
import hashlib
import importlib.util
import io
import json
import re
import sys
import tempfile
import unittest
from pathlib import Path
from typing import Any
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "check_mapping_contract", ROOT / "scripts/check_mapping_contract.py"
)
assert SPEC and SPEC.loader
contract = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = contract
SPEC.loader.exec_module(contract)

LIBRARY_URN = "urn:intuitem:risk:library:nist-sp-800-66-rev2"
FRAMEWORK_URN = "urn:intuitem:risk:framework:nist-sp-800-66-rev2"
PREFIX = "urn:intuitem:risk:req_node:nist-sp-800-66-rev2:"
_, TARGETS = contract.mapped_targets()


def escaped(text: str) -> str:
    """Double-quoted YAML content: backslash, quote and non-ASCII characters escaped."""
    out = []
    for char in text:
        if char in '\\"':
            out.append("\\" + char)
        elif ord(char) > 127:
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return "".join(out)


def name_lines(name: str, style: int) -> list[str]:
    """The name in one of four YAML styles, wrapped at a space where the style allows it."""
    head, _, tail = name.partition(" ")
    if style == 0 or not tail:
        return [f"      name: {name}"]
    if style == 1:
        return [f"      name: {head}", f"        {tail}"]
    if style == 2:
        # An escaped line break, then an escaped space, as YAML emitters write long strings.
        return [f'      name: "{escaped(head)}\\', f'        \\ {escaped(tail)}"']
    return [f"      name: '{head}", f"        {tail.replace(chr(39), chr(39) * 2)}'"]


def library(
    targets: list[tuple[str, str, str]], *, change: dict[str, dict[str, str]] | None = None
) -> bytes:
    change = change or {}
    sections = sorted({section for _, _, section in targets})
    lines = [
        f"urn: {LIBRARY_URN}",
        "locale: en",
        "name: Synthetic contract test library",
        "description: 'Generated by the contract tests from the repository mapping; not an",
        "  upstream document.'",
        "objects:",
        "  framework:",
        f"    urn: {FRAMEWORK_URN}",
        "    name: Synthetic framework",
        "    implementation_groups_definition:",
        "    - ref_id: R",
        "      name: Required",
        "    requirement_nodes:",
    ]
    for section in sections:
        lines += [
            f"    - urn: {PREFIX}{section}",
            "      assessable: false",
            "      depth: 2",
            f"      ref_id: '{section}'",
            '      description: "First line\\',
            '        \\ continued.\\n\\nSecond paragraph."',
        ]
    for index, (urn, name, section) in enumerate(targets):
        values = {"assessable": "true", "depth": "3", "section": section, "name": name}
        values.update(change.get(urn, {}))
        lines += [
            f"    - urn: {urn}",
            f"      assessable: {values['assessable']}",
            f"      depth: {values['depth']}",
            f"      parent_urn: {PREFIX}{values['section']}",
            *name_lines(values["name"], index % 4),
            "      implementation_groups:",
            "      - N",
            "      questions:",
            f"        {urn}:question:1:",
            "          type: text",
            "          text: A synthetic question with a long text that wraps onto the",
            "            next line?",
        ]
    return ("\n".join(lines) + "\n").encode()


def pin_for(data: bytes, **changes: Any) -> dict[str, Any]:
    text = data.decode()
    nodes = len(re.findall(r"^    - urn: ", text, re.MULTILINE))
    assessable = len(re.findall(r"^      assessable: true$", text, re.MULTILINE))
    pin = {
        "urn": LIBRARY_URN,
        "framework_urn": FRAMEWORK_URN,
        "commit": "0" * 40,
        "sha256": hashlib.sha256(data).hexdigest(),
        "requirement_nodes": nodes,
        "assessable_nodes": assessable,
    }
    pin.update(changes)
    return pin


class ContractTests(unittest.TestCase):
    def check(self, data: bytes, **pin: Any) -> list[str]:
        lines: list[str] = contract.check(data, pin_for(data, **pin))
        return lines

    def refused(self, data: bytes, needle: str, **pin: Any) -> None:
        with self.assertRaises(contract.ContractError) as raised:
            self.check(data, **pin)
        self.assertIn(needle, str(raised.exception))

    def test_a_matching_library_passes(self) -> None:
        lines = self.check(library(TARGETS))
        self.assertTrue(lines[0].startswith("PASS library sha256"))
        self.assertIn(f"PASS {len(TARGETS)} mapped URNs exist", lines[2])
        self.assertEqual(lines[3], "0 assessable nodes are not in the mapping")

    def test_every_name_style_decodes_to_the_mapped_name(self) -> None:
        parsed = contract.parse_library(library(TARGETS).decode())
        for urn, name, section in TARGETS:
            node = parsed.nodes[urn]
            self.assertEqual((node.name, node.parent_urn), (name, PREFIX + section))
        self.assertTrue(any(ord(char) > 127 for _, name, _ in TARGETS for char in name))
        self.assertEqual(contract.quoted('"a\\u2019b\\\n    \\ c"', '"'), "a" + chr(0x2019) + "b c")
        self.assertEqual(
            contract.quoted("'it''s\n   wrapped\n\n   here'", "'"), "it's wrapped\nhere"
        )

    def test_a_different_sha256_is_refused(self) -> None:
        self.refused(library(TARGETS), "differs from the pin", sha256="1" * 64)

    def test_missing_unassessable_renamed_or_moved_nodes_are_refused(self) -> None:
        urn, name, _ = TARGETS[5]
        cases = [
            ("is not in the library", library([t for t in TARGETS if t[0] != urn])),
            ("is not assessable at depth 3", library(TARGETS, change={urn: {"depth": "2"}})),
            ("is not assessable", library(TARGETS, change={urn: {"assessable": "false"}})),
            ("name differs", library(TARGETS, change={urn: {"name": name + " changed"}})),
            ("parent section differs", library(TARGETS, change={urn: {"section": "164.999"}})),
        ]
        for needle, data in cases:
            with self.subTest(needle=needle):
                self.refused(data, f"{urn} {needle}")

    def test_counts_and_urns_must_match_the_pin(self) -> None:
        data = library(TARGETS)
        self.refused(data, "the pin says", assessable_nodes=len(TARGETS) + 1)
        self.refused(data, "library URN differs", urn=LIBRARY_URN + "-other")
        self.refused(data, "framework URN differs", framework_urn=FRAMEWORK_URN + "-other")

    def test_unsupported_yaml_is_refused(self) -> None:
        text = library(TARGETS).decode()
        first = f"      name: {TARGETS[0][1]}\n"
        self.assertIn(first, text)
        cases = {
            "tab": text.replace("      depth: 3", "\tdepth: 3", 1),
            "block scalar": text.replace(first, "      name: |\n        Literal\n", 1),
            "anchor": text.replace(first, "      name: &anchor Name\n", 1),
            "flow": text.replace(first, "      name: [a, b]\n", 1),
            "unterminated": text.replace(first, '      name: "open\n', 1),
            "comment": text.replace(first, "      name: Name # note\n", 1),
            "structure": text.replace("      depth: 3\n", "      depth: 3\n     odd: x\n", 1),
            "duplicate key": text.replace(
                "      depth: 3\n", "      depth: 3\n      depth: 3\n", 1
            ),
        }
        for label, changed in cases.items():
            with self.subTest(label=label), self.assertRaises(contract.ContractError):
                contract.parse_library(changed)

    def test_download_refuses_an_unpinned_source_before_any_request(self) -> None:
        commit = "0" * 40
        for url in (
            "https://example.org/nist-sp-800-66-rev2.yaml",
            "http://raw.githubusercontent.com/intuitem/ciso-assistant-community/"
            f"{commit}/backend/library/libraries/nist-sp-800-66-rev2.yaml",
            "https://raw.githubusercontent.com/intuitem/ciso-assistant-community/"
            "main/backend/library/libraries/nist-sp-800-66-rev2.yaml",
        ):
            with (
                self.subTest(url=url),
                patch.object(contract.urllib.request, "urlopen") as opened,
                self.assertRaises(contract.ContractError),
            ):
                contract.download(url)
            opened.assert_not_called()

    def test_the_recorded_pin_names_the_v4_1_1_commit(self) -> None:
        pin = contract.load_pin()
        self.assertEqual(pin["commit"], "7a7a5babbdf9dffa10cafb454ff194be401e1aa0")
        self.assertIn(pin["commit"], pin["source"])
        self.assertTrue(pin["source"].endswith("/nist-sp-800-66-rev2.yaml"))
        self.assertEqual((pin["requirement_nodes"], pin["assessable_nodes"]), (179, 152))
        self.assertEqual(pin["framework_urn"], FRAMEWORK_URN)

    def test_main_checks_a_local_file(self) -> None:
        data = library(TARGETS)
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "library.yaml"
            path.write_bytes(data)
            output, errors = io.StringIO(), io.StringIO()
            with contextlib.redirect_stdout(output), contextlib.redirect_stderr(errors):
                self.assertEqual(contract.main([str(path)]), 1)
                with patch.object(contract, "load_pin", return_value=pin_for(data)):
                    self.assertEqual(contract.main([str(path)]), 0)
        self.assertIn("Mapping contract failed: library sha256", errors.getvalue())
        self.assertIn("PASS 117 mapped URNs exist", output.getvalue())

    def test_no_upstream_library_file_is_stored_in_the_repository(self) -> None:
        skipped = {".git", ".venv", ".data", ".cache", "site", "__pycache__", ".mypy_cache"}
        header = re.compile(r"^urn: urn:intuitem:risk:library:", re.MULTILINE)
        for path in ROOT.rglob("*"):
            if any(part in skipped for part in path.relative_to(ROOT).parts):
                continue
            if path.is_file() and path.suffix in {".yaml", ".yml", ".json"}:
                with self.subTest(path=str(path.relative_to(ROOT))):
                    self.assertIsNone(header.search(path.read_text(errors="replace")))


class MappingFileTests(unittest.TestCase):
    def test_targets_come_from_requirements_and_gaps(self) -> None:
        framework, targets = contract.mapped_targets()
        mapping = json.loads((ROOT / "mappings/hipaa-800-66r2.json").read_text())
        gaps = sum(len(gap["nodes"]) for gap in mapping["not_verified"])
        self.assertEqual(framework, FRAMEWORK_URN)
        self.assertEqual(len(targets), len(mapping["requirements"]) + gaps)
        self.assertEqual(len({urn for urn, _, _ in targets}), len(targets))


if __name__ == "__main__":
    unittest.main()
